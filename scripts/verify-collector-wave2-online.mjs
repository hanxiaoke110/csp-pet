import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const url = 'https://cards.cspstudy.top/collector-cards/catalog.json';
const response = await fetch(url,{cache:'no-store'});
assert(response.ok);
assert.equal(response.headers.get('access-control-allow-origin'),'*');
const online = await response.json();
const expected = JSON.parse(await readFile(resolve(root,'cloud-assets-source/collector-cards/catalog.json'),'utf8'));
assert.deepEqual(online,expected,'Online catalog not updated');
const before = JSON.parse(await readFile(resolve(root,'design/collector-cards-wave2/baseline-catalog.json'),'utf8'));
assert.deepEqual(online.cards.slice(0,before.cards.length),before.cards,'Old card definitions changed');
const jobs=online.cards.flatMap(card=>Object.entries(card.assets).map(([layer,path])=>({card,layer,url:new URL(path,url).href})));
let verified=0;
for(let i=0;i<jobs.length;i+=4) await Promise.all(jobs.slice(i,i+4).map(async job=>{
  const r=await fetch(job.url,{cache:'no-store'});
  assert(r.ok,`${job.card.name}/${job.layer}: ${r.status}`);
  assert(r.headers.get('content-type')?.startsWith('image/'),`${job.url}: not an image`);
  const bytes=Buffer.from(await r.arrayBuffer());
  const hash=createHash('sha256').update(bytes).digest('hex');
  assert.equal(hash,job.card.checksums[job.layer],`${job.card.name}/${job.layer}: hash mismatch`);
  verified++;
}));
const report={published:true,verifiedAt:new Date().toISOString(),catalogVersion:online.version,totalCards:online.cards.length,newCards:9,oldCardsPreserved:before.cards.length,verifiedAssets:verified,cloudflareVersion:'39b27df0-45b8-4ca0-b1f2-c8558847207b'};
await writeFile(resolve(root,'design/collector-cards-wave2/publication.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
