// Recovery helper: verify an exact CI artifact, then sign without exposing keys.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const [version, artifact] = process.argv.slice(2);
assert(/^\d+\.\d+\.\d+$/.test(version || ''));
const mapping = { 'macos-aarch64': ['darwin-aarch64', 'aarch64.dmg'], 'macos-x86_64': ['darwin-x86_64', 'x64.dmg'], 'windows-x86_64': ['windows-x86_64', 'x64-setup.exe'] };
assert(mapping[artifact]);
const [platform, suffix] = mapping[artifact];
const dir = `.tmp/v${version.replaceAll('.', '')}-candidate/${artifact}`;
const files = fs.readdirSync(dir).filter(x => /\.(dmg|exe)$/.test(x));
assert.equal(files.length, 1);
const file = path.join(dir, `CSP_${version}_${suffix}`);
const source = path.join(dir, files[0]);
if (source !== file) fs.renameSync(source, file);
const bytes = fs.readFileSync(file);
assert(bytes.length > 0 && bytes.length < 100000000, `${artifact} exceeds 100 MB`);
assert(platform.startsWith('windows') ? bytes.subarray(0, 2).toString() === 'MZ' : bytes.subarray(bytes.length - 512, bytes.length - 508).toString() === 'koly');
const stdout = execFileSync('npx', ['tauri', 'signer', 'sign', '--private-key-path', process.env.CSP_UPDATER_KEY_PATH || '/Users/hanliuliu/.tauri/csp-updater-v2.key', '--password', '', file], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
const signature = stdout.split('\n').find(line => /^dW50[A-Za-z0-9+/=]+$/.test(line.trim()))?.trim();
assert(signature);
const key = Buffer.from(JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json')).plugins.updater.pubkey, 'base64').toString().trim().split('\n')[1];
fs.writeFileSync(file + '.minisig', Buffer.from(signature, 'base64'));
execFileSync('minisign', ['-Vm', file, '-P', key, '-x', file + '.minisig'], { stdio: ['ignore', 'pipe', 'pipe'] });
const result = { platform, file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), signature };
fs.writeFileSync(dir + '/verified.json', JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({ platform, bytes: result.bytes, sha256: result.sha256, signatureVerified: true }));
